# Writes web/public/sign-in-bg.svg, the sign-in background (owner's request, M9).
# The NAMA mark repeated as concentric squares framing the card, each turned 4 degrees more and
# fading outwards (stroke opacity, no gradients), over a faint 40px grid.
# Run from web/: python3 icons/sign-in-bg.py
import xml.dom.minidom

CX, CY = 800, 500
BG, FG = '#0a0a0b', '#e4e4e7'  # the bg and primary tokens (docs/DESIGN.md)

rings = []
size, k = 440.0, 0
while size < 3600:
    opacity = max(0.05, 0.55 * 0.82**k)
    half = size / 2
    rings.append(
        f'  <rect x="{CX - half:.1f}" y="{CY - half:.1f}" width="{size:.1f}" height="{size:.1f}" '
        f'transform="rotate({k * 4} {CX} {CY})" fill="none" stroke="{FG}" '
        f'stroke-width="{3 if k == 0 else 2}" stroke-opacity="{opacity:.3f}"/>'
    )
    size *= 1.2
    k += 1

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="1000" viewBox="0 0 1600 1000" preserveAspectRatio="xMidYMid slice">
  <!-- Generated by web/icons/sign-in-bg.py. Do not edit by hand. -->
  <defs>
    <pattern id="grid" width="40" height="40" patternUnits="userSpaceOnUse" x="0" y="20">
      <rect x="0.5" y="0.5" width="39" height="39" fill="none" stroke="{FG}" stroke-opacity="0.035"/>
    </pattern>
  </defs>
  <rect width="1600" height="1000" fill="{BG}"/>
  <rect width="1600" height="1000" fill="url(#grid)"/>
{chr(10).join(rings)}
</svg>
'''
xml.dom.minidom.parseString(svg)  # fail loudly on broken XML
with open('public/sign-in-bg.svg', 'w') as f:
    f.write(svg)
print(f'public/sign-in-bg.svg: {len(svg)} bytes, {k} squares')
